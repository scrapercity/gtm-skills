#!/usr/bin/env node
// Regenerates references/scrapercity-catalog.md from the published `scrapercity` npm package.
//
// The npm package (MCP server + CLI) carries a generated catalog of every scraper tool,
// its endpoint, its input schema and its price. This script reads that catalog so the
// skills in this repo never drift from what ScraperCity actually exposes and charges.
//
//   node scripts/sync-catalog.mjs            # write the file
//   node scripts/sync-catalog.mjs --check    # exit 1 if the committed file is stale
//
// Requires Node 18+ and npm on PATH. No other dependencies.

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL, fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT = path.join(ROOT, 'references', 'scrapercity-catalog.md')
const CHECK = process.argv.includes('--check')

// Utility and database tools are hand-written in bin/mcp.mjs, not in the generated catalog.
// The script verifies each name still exists in the published server so this list cannot rot.
const UTILITY_TOOLS = [
  ['check_wallet', 'Balance, plan and billing date. Call before any paid run.'],
  ['list_runs', 'Recent runs with status, row counts and cost (hours up to 168, limit up to 100).'],
  ['check_run_status', 'RUNNING, SUCCEEDED, FAILED or CANCELLED, rows handled, download path.'],
  ['download_results', 'Saves the CSV of a SUCCEEDED run (outputPath optional).'],
  ['cancel_run', 'Stops a running job.'],
  ['query_lead_database', 'B2B Lead Database, up to 100 contacts per call. $149/mo plan and up.'],
  ['query_local_business_database', 'Local Business Database, up to 100 businesses per call. $149/mo plan and up.'],
]

// Price strings the published catalog renders wrong. Each entry says why it is overridden.
const PRICE_OVERRIDES = {
  // The package renders "$1.00" as ".00" (a "$1" replacement-string slip in its generator).
  // $1.00 per search with records found matches scrapercity.com/pricing (49 searches on the $49 plan).
  search_criminal_records: '$1.00 per search with records found (free when none are found)',
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], ...opts }).trim()
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'sc-catalog-'))
const version = sh('npm', ['view', 'scrapercity', 'version'])
const tarball = sh('npm', ['pack', `scrapercity@${version}`, '--silent'], { cwd: tmp }).split('\n').pop()
sh('tar', ['xzf', tarball], { cwd: tmp })
const pkg = path.join(tmp, 'package')
const { TOOLS, ENDPOINT_BY_TOOL } = await import(pathToFileURL(path.join(pkg, 'lib', 'catalog.generated.mjs')).href)
const mcpSource = fs.readFileSync(path.join(pkg, 'bin', 'mcp.mjs'), 'utf8')
const cliSource = fs.readFileSync(path.join(pkg, 'bin', 'cli.mjs'), 'utf8')

// Since scrapercity 1.0.24 the hand-written tools live in lib/utilityTools.mjs, shared by the MCP server and
// the JavaScript and Python SDKs; earlier versions define them in bin/mcp.mjs.
const utilPath = path.join(pkg, 'lib', 'utilityTools.mjs')
const utilityNames = fs.existsSync(utilPath) ? (await import(pathToFileURL(utilPath).href)).UTILITY_TOOLS.map((t) => t.name) : null
const missing = UTILITY_TOOLS.filter(([n]) => (utilityNames ? !utilityNames.includes(n) : !mcpSource.includes(`'${n}'`))).map(([n]) => n)
if (missing.length) {
  console.error(`FAIL: utility tools no longer in scrapercity@${version}: ${missing.join(', ')}`)
  process.exit(1)
}

const clean = (s) => String(s || '').replace(/[\u2013\u2014]/g, '-').replace(/\|/g, '/').replace(/\s+/g, ' ').trim()
const priceOf = (t) => {
  if (PRICE_OVERRIDES[t.name]) return PRICE_OVERRIDES[t.name]
  const m = /Cost: (.*?)\.?$/.exec(t.description)
  const p = m ? m[1] : ''
  if (/^\.\d/.test(p)) {
    console.error(`FAIL: malformed price text for ${t.name}: "${p}". Add it to PRICE_OVERRIDES with a reason.`)
    process.exit(1)
  }
  return p
}
const summaryOf = (t) => clean(t.description.split(' Cost:')[0])
const paramsOf = (t) => {
  const props = t.inputSchema?.properties || {}
  const req = new Set(t.inputSchema?.required || [])
  return Object.entries(props).map(([k, v]) => {
    const type = v.type === 'array' ? `${v.items?.type || 'object'}[]` : v.type || 'any'
    return `\`${k}\`${req.has(k) ? ' (required)' : ''}: ${type}. ${clean(v.description)}`
  })
}

const cliCommands = [...cliSource.matchAll(/case '([a-z-]+)':/g)].map((m) => m[1]).filter((c) => !['help', '--help', '-h'].includes(c))

const lines = []
lines.push('# ScraperCity Tool and Price Catalog')
lines.push('')
lines.push(`Generated by \`scripts/sync-catalog.mjs\` from the published \`scrapercity\` npm package, version ${version}.`)
lines.push('A later package version with the same tools, prices and CLI commands leaves this file unchanged.')
lines.push('Do not edit by hand. Run `node scripts/sync-catalog.mjs` to refresh, and `--check` in CI to catch drift.')
lines.push('Prices are per result and are deducted from the wallet. When this file and scrapercity.com/pricing disagree, the live site wins.')
lines.push('')
lines.push('## Access paths')
lines.push('')
lines.push('| Path | How | Best for |')
lines.push('|---|---|---|')
lines.push('| MCP server | `npx -y --package scrapercity scrapercity-mcp` with `SCRAPERCITY_API_KEY` in env | Claude Code, Claude Desktop, Cursor, Windsurf, Cline, any MCP client |')
lines.push('| CLI | `npx scrapercity <command>` after `npx scrapercity login` | Terminal work, shell scripts, cron jobs |')
lines.push('| REST API | `https://app.scrapercity.com/api/v1`, header `Authorization: Bearer <key>` | Clay, n8n, Zapier, Make, custom code |')
lines.push('| Dashboard | app.scrapercity.com | Point and click runs, CSV downloads, webhooks |')
lines.push('')
lines.push('## Utility and database tools (MCP)')
lines.push('')
lines.push('| Tool | What it does |')
lines.push('|---|---|')
for (const [n, d] of UTILITY_TOOLS) lines.push(`| \`${n}\` | ${d} |`)
lines.push('')
lines.push('## Scraper and enrichment tools (MCP), with endpoint and price')
lines.push('')
lines.push('| Tool | Endpoint (POST) | Price | What it returns |')
lines.push('|---|---|---|---|')
for (const t of TOOLS) lines.push(`| \`${t.name}\` | \`${ENDPOINT_BY_TOOL[t.name]}\` | ${clean(priceOf(t))} | ${summaryOf(t)} |`)
lines.push('')
lines.push('## Run lifecycle')
lines.push('')
lines.push('Every scraper follows the same pattern: start, poll, download.')
lines.push('')
lines.push('1. `POST /api/v1/scrape/{slug}` returns `{ runId }`.')
lines.push('2. `GET /api/v1/scrape/status/{runId}` returns `{ status, handled, requested, outputUrl }`. Status is `RUNNING`, then `SUCCEEDED`, `FAILED` or `CANCELLED`.')
lines.push('3. `GET /api/downloads/{runId}` returns the CSV once the run has SUCCEEDED.')
lines.push('')
lines.push('Apollo runs can take from hours up to several days. Register a webhook at app.scrapercity.com/dashboard/webhooks instead of polling; it fires when a run reaches SUCCEEDED or FAILED. If you must poll an Apollo run, check at most once an hour.')
lines.push('')
lines.push('## Error codes')
lines.push('')
lines.push('| Code | Meaning | What the agent should do |')
lines.push('|---|---|---|')
lines.push('| 401 | Missing or invalid API key | Stop and ask for a valid key. |')
lines.push('| 402 | Wallet balance too low | Run `check_wallet`, report the shortfall, wait for the user. |')
lines.push('| 403 | Account cancelled or a charge is processing | Stop and tell the user. |')
lines.push('| 409 | Same search submitted moments ago | Use the earlier run instead of resubmitting. |')
lines.push('| 429 | Rate limited | Back off, then retry once. |')
lines.push('| 503 | Temporarily unavailable, or a database search ran too long | Narrow the database search (add a location, size band or fewer titles), or retry later. |')
lines.push('')
lines.push('## CLI commands in this version')
lines.push('')
lines.push(cliCommands.map((c) => `\`${c}\``).join(', '))
lines.push('')
lines.push('## Input schemas')
lines.push('')
for (const t of TOOLS) {
  lines.push(`### \`${t.name}\``)
  lines.push('')
  for (const p of paramsOf(t)) lines.push(`- ${p}`)
  lines.push('')
}

const out = lines.join('\n')
fs.rmSync(tmp, { recursive: true, force: true })

// The package is published often, and most releases change no tool, price or CLI command.
// The version line alone is therefore not content: a file that differs from the package only
// there is current, so CI stays green and nothing needs a commit until the content moves.
const VERSION_LINE = /^Generated by `scripts\/sync-catalog\.mjs` from the published `scrapercity` npm package, version (\S+)\.$/m
const content = (s) => s.replace(VERSION_LINE, '')
const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
const recorded = (VERSION_LINE.exec(current) || [])[1]
const sameContent = current !== '' && recorded !== undefined && content(current) === content(out)
const firstDiff = () => {
  const a = content(current).split('\n')
  const b = content(out).split('\n')
  const i = a.findIndex((l, n) => l !== b[n])
  const n = i === -1 ? a.length : i
  return `first difference at line ${n + 1}: "${(b[n] ?? '').slice(0, 120)}"`
}

if (CHECK) {
  if (current === out) {
    console.log(`PASS: catalog matches scrapercity@${version}`)
  } else if (sameContent) {
    console.log(`PASS: catalog matches scrapercity@${version} (tools, prices and CLI commands unchanged since ${recorded})`)
  } else {
    console.error(`FAIL: references/scrapercity-catalog.md is stale against scrapercity@${version} (file has ${recorded || 'no version'}; ${firstDiff()}). Run node scripts/sync-catalog.mjs`)
    process.exit(1)
  }
} else if (sameContent) {
  console.log(`Unchanged: references/scrapercity-catalog.md (scrapercity@${version} has the same tools, prices and CLI commands as ${recorded})`)
} else {
  fs.writeFileSync(OUT, out)
  console.log(`Wrote references/scrapercity-catalog.md from scrapercity@${version} (${TOOLS.length} scraper tools, ${UTILITY_TOOLS.length} utility tools)`)
}
