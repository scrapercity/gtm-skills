#!/usr/bin/env python3
"""Write two repo-level indexes built from the skill folders.

  references/pitfalls-index.md  every row of every skill's "Common Pitfalls" section, grouped by skill
  taxonomy.csv                  one row per skill: category, version, path, description, related
                                skills, shared references, frameworks, and the ScraperCity tools
                                and prices named in its SKILL.md

  python3 scripts/generate-indexes.py          # write both files
  python3 scripts/generate-indexes.py --check  # exit 1 if either file is stale

Both files are for people and agents browsing the repo. Neither is packaged into a skill:
pitfalls-index.md must never be listed in a skill's metadata.shared_references.
Tool ids come from references/scrapercity-catalog.md, so a renamed tool shows up here too.
"""

from __future__ import annotations

import csv
import io
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PITFALLS = ROOT / "references" / "pitfalls-index.md"
TAXONOMY = ROOT / "taxonomy.csv"
CATALOG = ROOT / "references" / "scrapercity-catalog.md"
ORDER = ["scrapercity", "list-building", "outbound"]
TITLES = {"scrapercity": "ScraperCity platform", "list-building": "List building", "outbound": "Outbound"}
PRICE = re.compile(r"\$\d[\d,]*(?:\.\d+)?")


def skills() -> list[tuple[str, str, Path, dict, str]]:
    out = []
    for skill_md in sorted(ROOT.glob("skills/*/*/SKILL.md")):
        text = skill_md.read_text(encoding="utf-8")
        m = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
        if not m:
            raise SystemExit(f"{skill_md.relative_to(ROOT)}: missing frontmatter")
        fm = yaml.safe_load(m.group(1)) or {}
        out.append((skill_md.parent.parent.name, skill_md.parent.name, skill_md, fm, m.group(2)))
    rank = {c: i for i, c in enumerate(ORDER)}
    return sorted(out, key=lambda s: (rank.get(s[0], len(ORDER)), s[1]))


def section(body: str, title: str) -> list[str]:
    lines, inside = [], False
    for line in body.splitlines():
        if line.startswith("## "):
            inside = line[3:].strip() == title
            continue
        if inside:
            lines.append(line)
    return lines


def pitfall_rows(body: str) -> tuple[list[str], list[str]]:
    """Return (table header lines, item lines). Tables keep their rows; bullets stay bullets."""
    lines = [l.rstrip() for l in section(body, "Common Pitfalls")]
    table = [l for l in lines if l.startswith("|")]
    bullets = [l for l in lines if re.match(r"^(?:[-*]|\d+\.)\s", l)]
    if len(table) >= 3:
        return table[:2], table[2:]
    return [], bullets


def build_pitfalls(rows) -> str:
    total = 0
    blocks = []
    for cat in ORDER + sorted({r[0] for r in rows} - set(ORDER)):
        group = [r for r in rows if r[0] == cat]
        if not group:
            continue
        blocks.append(f"## {TITLES.get(cat, cat)}\n")
        for _, name, skill_md, _, body in group:
            header, items = pitfall_rows(body)
            total += len(items)
            rel = skill_md.relative_to(ROOT).as_posix()
            blocks.append(f"### [{name}](../{rel})\n")
            if not items:
                blocks.append("No Common Pitfalls rows found.\n")
                continue
            blocks.append("\n".join(header + items) + "\n")
    head = (
        "# Common Pitfalls Index\n\n"
        "Every row from the Common Pitfalls section of every skill, grouped by skill, so a reviewer "
        "or an agent can scan the known failure modes in one place. Each heading links to the skill "
        "that owns the rows; fix a row there, then regenerate.\n\n"
        "Generated by `scripts/generate-indexes.py`. Do not edit by hand. This file stays at the repo "
        "root and is not copied into any skill.\n\n"
        f"{total} pitfalls across {len(rows)} skills.\n"
    )
    return head + "\n" + "\n".join(blocks)


def catalog_tools() -> list[str]:
    tools, in_tools = [], False
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            in_tools = "tools" in line.lower()
            continue
        m = re.match(r"^\| `([a-z][a-z0-9_]+)` \|", line)
        if in_tools and m and m.group(1) not in tools:
            tools.append(m.group(1))
    if not tools:
        raise SystemExit("No tool ids found in references/scrapercity-catalog.md")
    return tools


def build_taxonomy(rows) -> str:
    tools = catalog_tools()
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow([
        "skill", "category", "version", "path", "description", "related_skills",
        "shared_references", "frameworks", "scrapercity_tools", "prices",
    ])
    for cat, name, skill_md, fm, body in rows:
        meta = fm.get("metadata") or {}
        frameworks = "; ".join(" ".join(str(f).split()) for f in meta.get("frameworks") or [])
        description = " ".join(str(fm.get("description") or "").split())
        text = f"{description}\n{body}"
        used = [t for t in tools if re.search(rf"\b{t}\b", text)]
        prices = sorted(set(PRICE.findall(text)), key=lambda p: (float(p[1:].replace(",", "")), p))
        w.writerow([
            name, cat, str(meta.get("version") or ""), skill_md.parent.relative_to(ROOT).as_posix(), description,
            " ".join(str(s) for s in meta.get("related_skills") or []),
            " ".join(str(s) for s in meta.get("shared_references") or []),
            frameworks, " ".join(used), " ".join(prices),
        ])
    return buf.getvalue()


def main(argv: list[str]) -> int:
    rows = skills()
    outputs = {PITFALLS: build_pitfalls(rows), TAXONOMY: build_taxonomy(rows)}
    if "--check" in argv:
        stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        if stale:
            for p in stale:
                print(f"FAIL - {p.relative_to(ROOT)} is stale (run scripts/generate-indexes.py)")
            return 1
        print("PASS - references/pitfalls-index.md and taxonomy.csv are current")
        return 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8")
        print(f"Wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
